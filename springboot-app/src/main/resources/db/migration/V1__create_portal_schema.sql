CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL,
    phone VARCHAR(25),
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role_supported CHECK (role IN ('ROLE_CITIZEN', 'ROLE_OFFICER', 'ROLE_ADMIN'))
);

CREATE INDEX idx_user_role ON users (role);

CREATE TABLE complaints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id VARCHAR(32) NOT NULL,
    title VARCHAR(150) NOT NULL,
    category VARCHAR(40) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    location VARCHAR(200) NOT NULL,
    citizen_name VARCHAR(100),
    citizen_email VARCHAR(100),
    citizen_phone VARCHAR(25),
    status VARCHAR(20) NOT NULL,
    admin_remark VARCHAR(2000),
    photo TEXT,
    citizen_user_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_complaints_complaint_id UNIQUE (complaint_id),
    CONSTRAINT fk_complaints_citizen FOREIGN KEY (citizen_user_id) REFERENCES users (id)
);

CREATE INDEX idx_complaint_status ON complaints (status);
CREATE INDEX idx_complaint_category ON complaints (category);

CREATE TABLE complaint_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id BIGINT NOT NULL,
    from_status VARCHAR(30),
    to_status VARCHAR(30) NOT NULL,
    remark VARCHAR(2000),
    updated_by VARCHAR(100),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_complaint FOREIGN KEY (complaint_id) REFERENCES complaints (id) ON DELETE CASCADE
);

CREATE INDEX idx_audit_complaint ON complaint_audit_logs (complaint_id);
CREATE INDEX idx_audit_created_at ON complaint_audit_logs (created_at);

CREATE TABLE officer_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id VARCHAR(32) NOT NULL,
    title VARCHAR(150) NOT NULL,
    citizen_name VARCHAR(100),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_notif_created ON officer_notifications (created_at);
CREATE INDEX idx_notif_read ON officer_notifications (is_read);
